-- Períodos com nome (temporadas), visíveis para todos. Só cria a tabela nova.
create table periods (
    id        bigint generated by default as identity primary key,
    name      varchar(100)             not null,
    from_date timestamp(6) with time zone not null,
    to_date   timestamp(6) with time zone,
    constraint ck_periods_from_before_to check (to_date is null or from_date < to_date)
);

create unique index ux_periods_name on periods (lower(name));
